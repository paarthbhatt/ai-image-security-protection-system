"""The committed evidence must describe itself, and must not describe one machine.

Three invariants, each born from something that actually went wrong here:

*   A report has to name the feature code that produced it. The copy-move group
    was dead for every run up to the fix and ``feature_count`` still read 143,
    because a registered constant is counted like any other feature. A version
    string in the artifact is what makes "stale evidence" a checkable claim.
*   The saved detector has to carry the layout it was fitted to, or scoring it
    later against a different ``feature_names()`` silently permutes columns.
*   Nothing committed may contain an absolute path. The project runs on other
    people's laptops; a home directory in a CSV is both a breakage and a leak.

The version-equality tests are deliberately strict: bumping ``FEATURE_VERSION``
without re-running makes them fail, and that is the point - the fix is to run the
pipeline, not to edit the assertion.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

import joblib

import features
from features import FEATURE_VERSION

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "reports" / "results.json"
MODEL = ROOT / "models" / "forensic_detector.joblib"
BENCHMARK = ROOT / "data" / "processed" / "benchmark_casia2.csv"


def _results() -> dict:
    with open(RESULTS, encoding="utf-8") as handle:
        return json.load(handle)


class ReportNamesItsGeneratorTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not RESULTS.is_file():
            raise unittest.SkipTest(f"{RESULTS} is generated by the pipeline")
        cls.data = _results()

    def test_the_report_records_the_feature_version(self):
        recorded = self.data["experiment"].get("feature_version")
        self.assertIsNotNone(
            recorded,
            "reports/results.json has no feature_version: re-run the pipeline so the "
            "evidence states which feature code produced it",
        )
        self.assertEqual(recorded, FEATURE_VERSION)

    def test_the_reported_feature_count_matches_the_live_layout(self):
        self.assertEqual(self.data["experiment"]["feature_count"], len(features.feature_names()))

    def test_split_sizes_add_up_to_the_rows(self):
        experiment = self.data["experiment"]
        self.assertEqual(
            experiment["train_instances"]
            + experiment["validation_instances"]
            + experiment["test_instances"],
            experiment["image_instances"],
        )

    def test_the_group_leakage_check_is_recorded_as_passed(self):
        self.assertTrue(self.data["group_leakage_check"]["passed"], self.data["group_leakage_check"])

    def test_the_point_estimate_lies_inside_its_own_confidence_interval(self):
        low, high = self.data["confidence_intervals"]["test_roc_auc"]
        auc = self.data["test"]["roc_auc"]
        self.assertLessEqual(low, auc)
        self.assertLessEqual(auc, high)

    def test_the_chosen_threshold_is_a_decision_threshold_not_a_default(self):
        threshold = self.data["test"]["threshold"]
        self.assertGreater(threshold, 0.0)
        self.assertLess(threshold, 1.0)

    def test_every_forgery_family_is_reported_with_the_metrics_it_claims(self):
        """``per_family`` is per forgery family, so authentic is not expected in it."""
        families = self.data["per_family"]
        self.assertTrue(families, "per_family is empty, so no family-level claim is checkable")
        for name, block in families.items():
            self.assertGreater(int(block["count"]), 0, name)
            for metric in ("roc_auc", "pr_auc", "recall"):
                value = float(block[metric])
                self.assertGreaterEqual(value, 0.0, f"{name}.{metric}")
                self.assertLessEqual(value, 1.0, f"{name}.{metric}")


class SavedDetectorTest(unittest.TestCase):
    """Loads the detector this repository itself wrote.

    ``joblib.load`` executes whatever the pickle contains, so the only thing
    that makes it safe is provenance: the path is inside this repository, the
    file is produced by ``src/train.py`` on the same machine, and the test skips
    when it is absent. It must never be pointed at a model from elsewhere.
    """

    @classmethod
    def setUpClass(cls) -> None:
        if not MODEL.is_file():
            raise unittest.SkipTest(f"{MODEL} is generated by the pipeline")
        cls.bundle = joblib.load(MODEL)

    def test_the_bundle_states_which_feature_code_it_was_fitted_on(self):
        self.assertEqual(self.bundle.get("feature_version"), FEATURE_VERSION)

    def test_the_stored_layout_is_the_live_layout(self):
        self.assertEqual(self.bundle["feature_names"], features.feature_names())

    def test_the_estimator_was_fitted_on_the_layout_it_ships_with(self):
        self.assertEqual(
            int(self.bundle["model"].n_features_in_), len(self.bundle["feature_names"])
        )

    def test_the_bundle_carries_the_decision_rule_and_its_provenance(self):
        self.assertIn(self.bundle["model_name"], {"logistic_regression", "random_forest",
                                                  "hist_gradient_boosting"})
        self.assertIsInstance(self.bundle["threshold"], float)
        self.assertIsInstance(self.bundle["seed"], int)
        self.assertTrue(self.bundle["corpus"])


class NoAbsolutePathTest(unittest.TestCase):
    """Generated artifacts describe a repository, not a workstation."""

    def _strings(self, node):
        if isinstance(node, str):
            yield node
        elif isinstance(node, dict):
            for value in node.values():
                yield from self._strings(value)
        elif isinstance(node, list):
            for value in node:
                yield from self._strings(value)

    def test_results_json_holds_no_absolute_paths(self):
        if not RESULTS.is_file():
            self.skipTest("no results.json yet")
        for text in self._strings(_results()):
            self.assertNotIn(str(Path.home()), text)
            if text.startswith("/") and len(text) > 1 and "." in Path(text).name:
                self.fail(f"absolute path committed in results.json: {text}")

    def test_benchmark_csv_path_columns_are_relative(self):
        if not BENCHMARK.is_file():
            self.skipTest("benchmark_casia2.csv is regenerated from data/real/ on demand")
        import csv

        with open(BENCHMARK, newline="", encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                for column in ("image_path", "mask_path"):
                    value = row.get(column) or ""
                    if not value:
                        continue
                    self.assertFalse(value.startswith("/"), f"{column} is absolute: {value}")
                    self.assertNotIn("..", value, f"{column} escapes the repository: {value}")


if __name__ == "__main__":
    unittest.main()
